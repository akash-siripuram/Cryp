/*
 * Inspects public/ and writes ASSET_CHECKLIST.md.
 * Status per file:
 *   MISSING   – not in public/
 *   PROBLEM   – present but unusable (too short/long, wrong resolution, unreadable)
 *   READY     – present and fits its slot in the edit
 * Exit code 1 with --strict when anything is not READY.
 */
import {execFileSync} from 'node:child_process';
import {existsSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {CUES, MUSIC_FILE, SFX, SHOTS, sourceSecondsNeeded} from '../src/timeline';

type Row = {group: string; file: string; slot: string; need: string; status: 'MISSING' | 'PROBLEM' | 'READY'; note: string};

const probe = (path: string) => {
	try {
		const out = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration:stream=codec_type,width,height', '-of', 'json', path]).toString();
		const j = JSON.parse(out);
		const v = (j.streams ?? []).find((s: {codec_type: string}) => s.codec_type === 'video');
		return {duration: parseFloat(j.format?.duration ?? 'NaN'), width: v?.width as number | undefined, height: v?.height as number | undefined};
	} catch {
		return null;
	}
};

const rows: Row[] = [];
const check = (group: string, file: string, slot: string, need: string, test: (p: NonNullable<ReturnType<typeof probe>>) => string | null) => {
	const path = join(process.env.PUBLIC_DIR ?? 'public', file);
	if (!existsSync(path)) return rows.push({group, file, slot, need, status: 'MISSING', note: ''});
	const p = probe(path);
	if (!p) return rows.push({group, file, slot, need, status: 'PROBLEM', note: 'Unreadable (is ffprobe installed? is the file valid?)'});
	const problem = test(p);
	rows.push({group, file, slot, need, status: problem ? 'PROBLEM' : 'READY', note: problem ?? `${p.duration.toFixed(2)} s${p.width ? `, ${p.width}×${p.height}` : ''}`});
};

const tc = (s: number) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, '0')}`;

for (const s of SHOTS) {
	const need = sourceSecondsNeeded(s);
	check('Footage', s.file, `${tc(s.start - s.dissolve)}–${tc(s.end)}`, `≥ ${need.toFixed(1)} s, 1920×1080`, (p) => {
		if (p.duration + 0.05 < need) return `Too short: ${p.duration.toFixed(2)} s`;
		if (!p.width || !p.height) return 'No video stream';
		if (p.width < 1920 || p.height < 1080) return `Low resolution ${p.width}×${p.height} (upscale to 1920×1080)`;
		if (Math.abs(p.width / p.height - 16 / 9) > 0.02) return `Aspect ${p.width}×${p.height} is not 16:9`;
		return null;
	});
}
for (const c of CUES) {
	const max = c.end - c.start + 0.3;
	check('Narration', c.file, `${tc(c.start)}–${tc(c.end)}`, `≤ ${max.toFixed(1)} s`, (p) => (p.duration > max ? `Too long: ${p.duration.toFixed(2)} s — tighten the read or trim silence` : null));
}
check('Music', MUSIC_FILE, '0:00–2:00', '≥ 119.5 s', (p) => (p.duration < 119.5 ? `Too short: ${p.duration.toFixed(1)} s` : null));
for (const file of Array.from(new Set(SFX.map((s) => s.file)))) {
	const uses = SFX.filter((s) => s.file === file);
	check('Sound effects', file, uses.map((u) => tc(u.start)).join(', '), uses.some((u) => u.loop) ? 'loopable bed' : 'one-shot', (p) => (p.duration < 0.3 ? 'Too short' : null));
}

const count = (st: Row['status']) => rows.filter((r) => r.status === st).length;
const ready = count('READY') === rows.length;
const icon = {MISSING: '⬜ MISSING', PROBLEM: '⚠️ PROBLEM', READY: '✅ READY'};

let md = `# Asset Checklist\n\nGenerated by \`npm run assets\` from the files actually present in \`public/\` (re-run after adding files).\n\n`;
md += `**${count('READY')} ready · ${count('PROBLEM')} with problems · ${count('MISSING')} missing · ${rows.length} total**\n\n`;
md += ready ? '**Ready for final render:** `npm run render`\n\n' : '**Not ready for the final render.** The film still renders, but missing footage shows labeled slates and missing audio is silent.\n\n';
for (const g of ['Footage', 'Narration', 'Music', 'Sound effects']) {
	const rs = rows.filter((r) => r.group === g);
	md += `## ${g} (${rs.filter((r) => r.status === 'READY').length}/${rs.length} ready)\n\n| Status | File (in public/) | Used at | Requirement | Notes |\n|---|---|---|---|---|\n`;
	md += rs.map((r) => `| ${icon[r.status]} | \`${r.file}\` | ${r.slot} | ${r.need} | ${r.note} |`).join('\n') + '\n\n';
}
writeFileSync('ASSET_CHECKLIST.md', md);
console.log(`ASSET_CHECKLIST.md: ${count('READY')} ready, ${count('PROBLEM')} problems, ${count('MISSING')} missing of ${rows.length}`);
rows.filter((r) => r.status === 'PROBLEM').forEach((r) => console.log(`  ⚠ ${r.file}: ${r.note}`));
if (process.argv.includes('--strict') && !ready) process.exit(1);
